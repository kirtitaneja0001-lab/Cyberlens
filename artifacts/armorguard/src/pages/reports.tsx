import { MainLayout } from "@/components/layout/main-layout";
import { useStore } from "@/hooks/use-store";
import { Button } from "@/components/ui/button";
import { Download, FileText, Calendar, ShieldAlert } from "lucide-react";
import jsPDF from "jspdf";
import { format } from "date-fns";

export default function Reports() {
  const { scans } = useStore();
  const completedScans = scans.filter(s => s.status === 'completed');

  const generatePDF = (scan: any) => {
    const doc = new jsPDF();
    
    // Header
    doc.setFont("helvetica", "bold");
    doc.setFontSize(24);
    doc.setTextColor(242, 106, 46); // Accent orange
    doc.text("ArmorGuard", 20, 20);
    
    doc.setFontSize(14);
    doc.setTextColor(100, 100, 100);
    doc.text("Security Intelligence Report", 20, 28);
    
    doc.setDrawColor(242, 106, 46);
    doc.setLineWidth(1);
    doc.line(20, 32, 190, 32);

    // Metadata
    doc.setFontSize(10);
    doc.setTextColor(0, 0, 0);
    doc.text(`Target: \${scan.target}`, 20, 45);
    doc.text(`Date: \${format(new Date(scan.startTime), 'PPP')}`, 20, 52);
    doc.text(`Scan Type: \${scan.type}`, 20, 59);
    doc.text(`Duration: \${scan.duration}`, 20, 66);
    
    // Risk Score
    doc.setFontSize(16);
    doc.text("Risk Score:", 140, 45);
    doc.setFontSize(28);
    doc.setTextColor(scan.riskScore > 80 ? 255 : scan.riskScore > 40 ? 242 : 34, scan.riskScore > 80 ? 0 : 106, 0); // Red, Orange, Green approx
    doc.text(`\${scan.riskScore}/100`, 140, 60);

    // Exec Summary
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    doc.text("Executive Summary", 20, 85);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    const summaryText = `The ArmorGuard automated scanning engine performed a \${scan.type} security assessment against \${scan.target}. The scan identified several potential security vulnerabilities that require attention. The overall risk posture is considered \${scan.riskScore > 80 ? 'CRITICAL' : scan.riskScore > 40 ? 'ELEVATED' : 'MODERATE'}.`;
    const splitSummary = doc.splitTextToSize(summaryText, 170);
    doc.text(splitSummary, 20, 95);

    // Findings
    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    doc.text("Key Findings", 20, 125);
    
    let yPos = 135;
    const fakeFindings = [
      { t: "Missing Content Security Policy", s: "Medium" },
      { t: "Server Banner Information Disclosure", s: "Low" }
    ];
    if (scan.riskScore > 80) fakeFindings.unshift({ t: "SQL Injection Vulnerability in /api/v1/auth", s: "Critical" });
    if (scan.riskScore > 40) fakeFindings.unshift({ t: "Open Port 3306 Exposed", s: "High" });

    doc.setFontSize(10);
    fakeFindings.forEach(f => {
      doc.setFont("helvetica", "bold");
      doc.text(`[\${f.s}]`, 20, yPos);
      doc.setFont("helvetica", "normal");
      doc.text(f.t, 45, yPos);
      yPos += 10;
    });

    // Footer
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text("Generated by ArmorGuard Security Intelligence - armorguard.io", 20, 280);

    doc.save(`armorguard-report-\${scan.target.replace(/[^a-z0-9]/gi, '_')}-\${format(new Date(scan.startTime), 'yyyy-MM-dd')}.pdf`);
  };

  return (
    <MainLayout>
      <div className="flex flex-col gap-6">
        <div>
          <h1 className="text-2xl font-bold tracking-tight">Reports Library</h1>
          <p className="text-sm text-muted-foreground">Download and share security assessment reports</p>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-4">
          {completedScans.map((scan) => (
            <div key={scan.id} className="bg-[#111111] border border-[rgba(255,255,255,0.06)] rounded-lg p-5 flex flex-col group hover:border-[rgba(255,255,255,0.15)] transition-colors">
              <div className="flex justify-between items-start mb-4">
                <div className="p-2 bg-[#0A0A0A] rounded-md border border-[rgba(255,255,255,0.05)]">
                  <FileText className="w-5 h-5 text-accent" />
                </div>
                <div className="flex items-center gap-1 font-mono text-sm px-2 py-1 rounded bg-[#0A0A0A] border border-[rgba(255,255,255,0.05)]">
                  <ShieldAlert className="w-3 h-3 text-muted-foreground" />
                  {scan.riskScore}
                </div>
              </div>
              
              <h3 className="font-medium text-lg truncate" title={scan.target}>{scan.target}</h3>
              
              <div className="mt-2 space-y-2 mb-6">
                <div className="flex items-center gap-2 text-xs text-muted-foreground">
                  <Calendar className="w-3.5 h-3.5" />
                  {format(new Date(scan.startTime), 'PPP')}
                </div>
                <div className="flex gap-2">
                  <span className="text-[10px] px-1.5 py-0.5 rounded bg-red-500/10 text-red-400">1 Critical</span>
                  <span className="text-[10px] px-1.5 py-0.5 rounded bg-accent/10 text-accent">2 High</span>
                </div>
              </div>

              <div className="mt-auto pt-4 border-t border-[rgba(255,255,255,0.06)]">
                <Button 
                  variant="ghost" 
                  className="w-full justify-center gap-2 text-muted-foreground hover:text-white hover:bg-white/5"
                  onClick={() => generatePDF(scan)}
                >
                  <Download className="w-4 h-4" />
                  Download PDF
                </Button>
              </div>
            </div>
          ))}
          {completedScans.length === 0 && (
            <div className="col-span-full py-12 text-center text-muted-foreground border border-dashed border-[rgba(255,255,255,0.1)] rounded-lg">
              No completed scan reports available yet.
            </div>
          )}
        </div>
      </div>
    </MainLayout>
  );
}
